func workPatternHash(value []byte) string {
	sum := sha256.Sum256(value)
	return hex.EncodeToString(sum[:])
}

func workPatternClamp(value float64) float64 {
	return math.Max(0, math.Min(1, value))
}

func normalizeWorkPatternAppKey(bundleID, appName string) string {
	if value := strings.ToLower(strings.TrimSpace(bundleID)); value != "" {
		return value
	}
	value := strings.ToLower(strings.Join(strings.Fields(appName), " "))
	if value == "" {
		return ""
	}
	return "name:" + value
}

func workPatternIsAmbientSystemApp(appKey, appName string) bool {
	// Preserve the historical work-pattern result while sharing the matcher
	// with readable evidence's broader presentation exclusions.
	return isSystemNoiseApp(appName, appKey) && systemNoiseAppClass(appName, appKey) == 1
}

func filterWorkPatternSourceEvents(
	events []workPatternSourceEvent,
) ([]workPatternSourceEvent, int) {
	result := make([]workPatternSourceEvent, 0, len(events))
	excluded := 0
	for _, event := range events {
		if workPatternIsAmbientSystemApp(event.AppKey, event.AppName) {
			excluded++
			continue
		}
		result = append(result, event)
	}
	return result, excluded
}

func workPatternDisplayAppName(value string) string {
	value = strings.Join(strings.Fields(strings.TrimSpace(value)), " ")
	if value == "" {
		return "Unknown application"
	}
	redacted, _ := pii.RedactText(value)
	if strings.TrimSpace(redacted) == "" {
		return "Protected application"
	}
	return strings.TrimSpace(redacted)
}

func workPatternPercentile(values []float64, percentile float64) float64 {
	if len(values) == 0 {
		return 0
	}
	sorted := append([]float64(nil), values...)
	sort.Float64s(sorted)
	if len(sorted) == 1 {
		return sorted[0]
	}
	position := workPatternClamp(percentile) * float64(len(sorted)-1)
	lower := int(math.Floor(position))
	upper := int(math.Ceil(position))
	if lower == upper {
		return sorted[lower]
	}
	weight := position - float64(lower)
	return sorted[lower]*(1-weight) + sorted[upper]*weight
}

func workPatternRobustSeries(
	values []float64,
) ([]float64, int, float64) {
	if len(values) == 0 {
		return []float64{}, 0, 0
	}
	sorted := append([]float64(nil), values...)
	sort.Float64s(sorted)
	lower := workPatternPercentile(sorted, 0.05)
	upper := workPatternPercentile(sorted, 0.95)
	if len(sorted) < 10 {
		lower = sorted[0]
		upper = sorted[len(sorted)-1]
	}
	result := make([]float64, len(values))
	outliers := 0
	for index, value := range values {
		switch {
		case value < lower:
			result[index] = lower
			outliers++
		case value > upper:
			result[index] = upper
			outliers++
		default:
			result[index] = value
		}
	}
	median := math.Abs(workPatternPercentile(result, 0.50))
	iqr := workPatternPercentile(result, 0.75) -
		workPatternPercentile(result, 0.25)
	stability := 1 - workPatternClamp(iqr/math.Max(median, 1))
	return result, outliers, stability
}

func workPatternDecayWeight(freshnessAt, cutoffAt int64) float64 {
	if freshnessAt <= 0 || cutoffAt <= 0 || freshnessAt >= cutoffAt {
		return 1
	}
	age := time.Duration(cutoffAt-freshnessAt) * time.Millisecond
	return workPatternClamp(math.Pow(
		0.5,
		float64(age)/float64(workPatternProfileDecayHalfLife),
	))
}

func workPatternMetricConfidence(samples, target int) float64 {
	if samples <= 0 || target <= 0 {
		return 0
	}
	return workPatternClamp(float64(samples) / float64(target))
}

func enrichWorkPatternMetric(
	metric WorkPatternMetric,
	windowStart, windowEnd, cutoffAt int64,
	stability float64,
	outlierCount int,
) WorkPatternMetric {
	metric.SourceWindowStart = windowStart
	metric.SourceWindowEnd = windowEnd
	metric.Stability = workPatternClamp(stability)
	metric.OutlierCount = max(outlierCount, 0)
	metric.DecayWeight = workPatternDecayWeight(windowEnd, cutoffAt)
	metric.Confidence = workPatternClamp(
		metric.Confidence * metric.DecayWeight,
	)
	return metric
}

func workPatternMetric(
	name string,
	value float64,
	unit string,
	samples, target int,
) WorkPatternMetric {
	return WorkPatternMetric{
		Name:        name,
		Value:       value,
		Unit:        unit,
		SampleCount: samples,
		Confidence:  workPatternMetricConfidence(samples, target),
	}
}

func workPatternRunRef(run workPatternRun) string {
	return workPatternHash([]byte(strings.Join([]string{
		run.SessionID,
		run.AppKey,
		fmt.Sprint(run.StartAt),
		fmt.Sprint(run.EndAt),
	}, "\x00")))
}

func workPatternSessionRef(sessionID string) string {
	return workPatternHash([]byte("session\x00" + sessionID))
}

func workPatternProjectionThresholds(scope string) (int, int) {
	switch scope {
	case WorkPatternScopeApp:
		return 5, 2
	case WorkPatternScopeTransition:
		return 3, 2
	case WorkPatternScopeWorkMode:
		return 6, 2
	default:
		return workPatternProfileMinimumRuns, workPatternProfileMinimumSessions
	}
}

func buildWorkPatternProjection(
	scopeKind, scopeKey, label string,
	apps []string,
	cutoffAt int64,
	runs []workPatternRun,
	extraMetrics []WorkPatternMetric,
) WorkPatternProjection {
	sessionApps := make(map[string]map[string]struct{})
	lastEndBySessionApp := make(map[string]int64)
	sessionSeen := make(map[string]struct{})
	dwellSeconds := make([]float64, 0, len(runs))
	returnSeconds := make([]float64, 0)
	inactivitySeconds := make([]float64, 0)
	resumedWithinWindow := 0
	activeMilliseconds := int64(0)
	switches := 0
	windowStart := int64(0)
	windowEnd := int64(0)
	lastAppBySession := make(map[string]string)
	lastRunBySession := make(map[string]workPatternRun)
	intervalRefs := make(map[string]struct{})
	sessionRefs := make(map[string]struct{})

	for _, run := range runs {
		if run.EndAt <= run.StartAt || run.AppKey == "" {
			continue
		}
		duration := run.EndAt - run.StartAt
		if windowStart == 0 || run.StartAt < windowStart {
			windowStart = run.StartAt
		}
		windowEnd = max(windowEnd, run.EndAt)
		dwellSeconds = append(dwellSeconds, float64(duration)/1000)
		activeMilliseconds += duration
		sessionSeen[run.SessionID] = struct{}{}
		intervalRefs[workPatternRunRef(run)] = struct{}{}
		sessionRefs[workPatternSessionRef(run.SessionID)] = struct{}{}
		if sessionApps[run.SessionID] == nil {
			sessionApps[run.SessionID] = make(map[string]struct{})
		}
		sessionApps[run.SessionID][run.AppKey] = struct{}{}
		if previous := lastAppBySession[run.SessionID]; previous != "" &&
			previous != run.AppKey {
			switches++
		}
		lastAppBySession[run.SessionID] = run.AppKey
		if previous, ok := lastRunBySession[run.SessionID]; ok &&
			run.StartAt > previous.EndAt {
			inactivitySeconds = append(
				inactivitySeconds,
				float64(run.StartAt-previous.EndAt)/1000,
			)
		}
		lastRunBySession[run.SessionID] = run

		returnKey := run.SessionID + "\x00" + run.AppKey
		if previousEnd := lastEndBySessionApp[returnKey]; previousEnd > 0 &&
			run.StartAt >= previousEnd {
			gap := run.StartAt - previousEnd
			returnSeconds = append(returnSeconds, float64(gap)/1000)
			if gap <= workPatternProfileResumeWindow.Milliseconds() {
				resumedWithinWindow++
			}
		}
		lastEndBySessionApp[returnKey] = run.EndAt
	}
	robustDwell, dwellOutliers, dwellStability :=
		workPatternRobustSeries(dwellSeconds)
	robustReturns, returnOutliers, returnStability :=
		workPatternRobustSeries(returnSeconds)
	robustInactivity, inactivityOutliers, inactivityStability :=
		workPatternRobustSeries(inactivitySeconds)

	distinctApps := make([]float64, 0, len(sessionApps))
	for _, values := range sessionApps {
		distinctApps = append(distinctApps, float64(len(values)))
	}
	metrics := []WorkPatternMetric{
		workPatternMetric(
			"median_dwell_seconds",
			workPatternPercentile(robustDwell, 0.50),
			"seconds",
			len(dwellSeconds),
			20,
		),
		workPatternMetric(
			"p90_dwell_seconds",
			workPatternPercentile(robustDwell, 0.90),
			"seconds",
			len(dwellSeconds),
			20,
		),
	}
	if activeMilliseconds > 0 {
		metrics = append(metrics, workPatternMetric(
			"switches_per_active_hour",
			float64(switches)/(float64(activeMilliseconds)/float64(time.Hour.Milliseconds())),
			"switches_per_hour",
			switches,
			20,
		))
	}
	if len(returnSeconds) > 0 {
		metrics = append(metrics,
			workPatternMetric(
				"median_return_seconds",
				workPatternPercentile(robustReturns, 0.50),
				"seconds",
				len(returnSeconds),
				12,
			),
			workPatternMetric(
				"resume_within_15m_rate",
				float64(resumedWithinWindow)/float64(len(returnSeconds)),
				"ratio",
				len(returnSeconds),
				12,
			),
		)
	}
	if len(inactivitySeconds) > 0 {
		metrics = append(
			metrics,
			workPatternMetric(
				"inactivity_gap_count",
				float64(len(inactivitySeconds)),
				"count",
				len(inactivitySeconds),
				8,
			),
			workPatternMetric(
				"median_inactivity_gap_seconds",
				workPatternPercentile(robustInactivity, 0.50),
				"seconds",
				len(inactivitySeconds),
				8,
			),
		)
	}
	if len(distinctApps) > 0 {
		total := float64(0)
		for _, value := range distinctApps {
			total += value
		}
		metrics = append(metrics, workPatternMetric(
			"mean_distinct_apps_per_session",
			total/float64(len(distinctApps)),
			"apps",
			len(distinctApps),
			8,
		))
	}
	metrics = append(metrics, extraMetrics...)
	totalStability := float64(0)
	for index := range metrics {
		stability := metrics[index].Confidence
		outliers := 0
		switch metrics[index].Name {
		case "median_dwell_seconds", "p90_dwell_seconds":
			stability = dwellStability
			outliers = dwellOutliers
		case "median_return_seconds", "resume_within_15m_rate":
			stability = returnStability
			outliers = returnOutliers
		case "inactivity_gap_count", "median_inactivity_gap_seconds":
			stability = inactivityStability
			outliers = inactivityOutliers
		}
		metrics[index] = enrichWorkPatternMetric(
			metrics[index],
			windowStart,
			windowEnd,
			cutoffAt,
			stability,
			outliers,
		)
		totalStability += metrics[index].Stability
	}

	minimumRuns, minimumSessions := workPatternProjectionThresholds(scopeKind)
	status := WorkPatternProfileStatusInsufficient
	if len(dwellSeconds) >= minimumRuns && len(sessionSeen) >= minimumSessions {
		status = WorkPatternProfileStatusQualified
	}
	confidence := workPatternClamp(
		0.60*float64(len(dwellSeconds))/float64(max(minimumRuns*3, 1)) +
			0.40*float64(len(sessionSeen))/float64(max(minimumSessions*3, 1)),
	)
	if status == WorkPatternProfileStatusInsufficient {
		confidence = math.Min(confidence, 0.69)
	}
	decayWeight := workPatternDecayWeight(windowEnd, cutoffAt)
	confidence = workPatternClamp(confidence * decayWeight)
	projectionStability := float64(0)
	if len(metrics) > 0 {
		projectionStability = totalStability / float64(len(metrics))
	}
	sortedIntervalRefs := make([]string, 0, len(intervalRefs))
	for ref := range intervalRefs {
		sortedIntervalRefs = append(sortedIntervalRefs, ref)
	}
	sort.Strings(sortedIntervalRefs)
	sortedSessionRefs := make([]string, 0, len(sessionRefs))
	for ref := range sessionRefs {
		sortedSessionRefs = append(sortedSessionRefs, ref)
	}
	sort.Strings(sortedSessionRefs)

	return WorkPatternProjection{
		ScopeKind:    scopeKind,
		ScopeKey:     scopeKey,
		Label:        strings.TrimSpace(label),
		EvidenceKind: WorkPatternEvidenceObserved,
		Status:       status,
		Confidence:   confidence,
		SampleCount:  len(dwellSeconds),
		SessionCount: len(sessionSeen),
		FreshnessAt:  windowEnd,
		Stability:    workPatternClamp(projectionStability),
		DecayWeight:  decayWeight,
		Apps:         uniqueSortedStrings(apps),
		IntervalRefs: sortedIntervalRefs,
		SessionRefs:  sortedSessionRefs,
		Metrics:      metrics,
	}
}

func deriveWorkPatternRuns(
	events []workPatternSourceEvent,
) ([]workPatternRun, []workPatternTransition) {
	bySession := make(map[string][]workPatternSourceEvent)
	for _, event := range events {
		bySession[event.SessionID] = append(bySession[event.SessionID], event)
	}
	sessionIDs := make([]string, 0, len(bySession))
	for sessionID := range bySession {
		sessionIDs = append(sessionIDs, sessionID)
	}
	sort.Strings(sessionIDs)

	runs := make([]workPatternRun, 0, len(events))
	transitions := make([]workPatternTransition, 0, len(events))
	for _, sessionID := range sessionIDs {
		sessionEvents := bySession[sessionID]
		sort.SliceStable(sessionEvents, func(i, j int) bool {
			if sessionEvents[i].Timestamp != sessionEvents[j].Timestamp {
				return sessionEvents[i].Timestamp < sessionEvents[j].Timestamp
			}
			return sessionEvents[i].RowID < sessionEvents[j].RowID
		})
		sessionRuns := make([]workPatternRun, 0)
		var current *workPatternRun
		lastEventAt := int64(0)
		sessionEnd := int64(0)
		for _, event := range sessionEvents {
			if event.AppKey == "" {
				continue
			}
			if event.SessionEnd > sessionEnd {
				sessionEnd = event.SessionEnd
			}
			startNew := current == nil || current.AppKey != event.AppKey
			if current != nil && lastEventAt > 0 &&
				event.Timestamp-lastEventAt > workPatternProfileIdleGap.Milliseconds() {
				startNew = true
			}
			if startNew {
				if current != nil {
					end := event.Timestamp
					if lastEventAt > 0 &&
						end-lastEventAt > workPatternProfileIdleGap.Milliseconds() {
						end = lastEventAt + workPatternProfileIdleGap.Milliseconds()
					}
					if end <= current.StartAt {
						end = current.StartAt + 1000
					}
					current.EndAt = end
					sessionRuns = append(sessionRuns, *current)
				}
				current = &workPatternRun{
					SessionID: sessionID,
					AppKey:    event.AppKey,
					AppName:   event.AppName,
					StartAt:   event.Timestamp,
				}
			}
			lastEventAt = event.Timestamp
		}
		if current != nil {
			end := sessionEnd
			if end <= current.StartAt {
				end = current.StartAt + 1000
			}
			if end-current.StartAt > workPatternProfileIdleGap.Milliseconds() {
				end = current.StartAt + workPatternProfileIdleGap.Milliseconds()
			}
			current.EndAt = end
			sessionRuns = append(sessionRuns, *current)
		}
		for index, run := range sessionRuns {
			runs = append(runs, run)
			if index == 0 {
				continue
			}
			previous := sessionRuns[index-1]
			if previous.AppKey == run.AppKey ||
				run.StartAt-previous.EndAt > workPatternProfileIdleGap.Milliseconds() {
				continue
			}
			transitions = append(transitions, workPatternTransition{
				SessionID:   sessionID,
				Source:      previous,
				Destination: run,
			})
		}
	}
	sort.SliceStable(runs, func(i, j int) bool {
		if runs[i].StartAt != runs[j].StartAt {
			return runs[i].StartAt < runs[j].StartAt
		}
		if runs[i].SessionID != runs[j].SessionID {
			return runs[i].SessionID < runs[j].SessionID
		}
		return runs[i].AppKey < runs[j].AppKey
	})
	return runs, transitions
}

func workPatternModeKey(
	sessionRuns []workPatternRun,
) (string, string, []string) {
	type appUsage struct {
		key      string
		name     string
		activeMs int64
	}
	usageByApp := make(map[string]*appUsage)
	for _, run := range sessionRuns {
		item := usageByApp[run.AppKey]
		if item == nil {
			item = &appUsage{key: run.AppKey, name: run.AppName}
			usageByApp[run.AppKey] = item
		}
		item.activeMs += max(run.EndAt-run.StartAt, int64(0))
	}
	usage := make([]appUsage, 0, len(usageByApp))
	for _, item := range usageByApp {
		usage = append(usage, *item)
	}
	sort.SliceStable(usage, func(i, j int) bool {
		if usage[i].activeMs != usage[j].activeMs {
			return usage[i].activeMs > usage[j].activeMs
		}
		return usage[i].key < usage[j].key
	})
	if len(usage) < 2 {
		return "", "", nil
	}
	if len(usage) > workPatternProfileMaxModeApps {
		usage = usage[:workPatternProfileMaxModeApps]
	}
	keys := make([]string, 0, len(usage))
	names := make([]string, 0, len(usage))
	for _, item := range usage {
		keys = append(keys, item.key)
		names = append(names, item.name)
	}
	sort.Strings(keys)
	return strings.Join(keys, "+"), strings.Join(names, " + "), keys
}

func buildWorkPatternProjections(
	runs []workPatternRun,
	transitions []workPatternTransition,
	cutoffAt int64,
) []WorkPatternProjection {
	projections := []WorkPatternProjection{
		buildWorkPatternProjection(
			WorkPatternScopeGlobal,
			"all",
			"All observed work",
			nil,
			cutoffAt,
			runs,
			nil,
		),
	}

	runsByApp := make(map[string][]workPatternRun)
	appNames := make(map[string]string)
	runsBySession := make(map[string][]workPatternRun)
	for _, run := range runs {
		runsByApp[run.AppKey] = append(runsByApp[run.AppKey], run)
		runsBySession[run.SessionID] = append(runsBySession[run.SessionID], run)
		if appNames[run.AppKey] == "" {
			appNames[run.AppKey] = run.AppName
		}
	}
	appKeys := make([]string, 0, len(runsByApp))
	for appKey := range runsByApp {
		appKeys = append(appKeys, appKey)
	}
	sort.Strings(appKeys)
	for _, appKey := range appKeys {
		projections = append(projections, buildWorkPatternProjection(
			WorkPatternScopeApp,
			appKey,
			appNames[appKey],
			[]string{appKey},
			cutoffAt,
			runsByApp[appKey],
			nil,
		))
	}

	transitionsByPair := make(map[string][]workPatternTransition)
	for _, transition := range transitions {
		key := transition.Source.AppKey + "->" + transition.Destination.AppKey
		transitionsByPair[key] = append(transitionsByPair[key], transition)
	}
	pairs := make([]string, 0, len(transitionsByPair))
	for pair := range transitionsByPair {
		pairs = append(pairs, pair)
	}
	sort.Strings(pairs)
	for _, pair := range pairs {
		items := transitionsByPair[pair]
		destinationRuns := make([]workPatternRun, 0, len(items))
		sessions := make(map[string]struct{})
		for _, item := range items {
			destinationRuns = append(destinationRuns, item.Destination)
			sessions[item.SessionID] = struct{}{}
		}
		first := items[0]
		projections = append(projections, buildWorkPatternProjection(
			WorkPatternScopeTransition,
			pair,
			first.Source.AppName+" to "+first.Destination.AppName,
			[]string{first.Source.AppKey, first.Destination.AppKey},
			cutoffAt,
			destinationRuns,
			[]WorkPatternMetric{workPatternMetric(
				"transition_count",
				float64(len(items)),
				"count",
				len(items),
				8,
			), workPatternMetric(
				"transition_session_count",
				float64(len(sessions)),
				"count",
				len(sessions),
				4,
			)},
		))
	}

	type modeAccumulator struct {
		label      string
		apps       []string
		sessionIDs map[string]struct{}
		runs       []workPatternRun
	}
	modes := make(map[string]*modeAccumulator)
	sessionIDs := make([]string, 0, len(runsBySession))
	for sessionID := range runsBySession {
		sessionIDs = append(sessionIDs, sessionID)
	}
	sort.Strings(sessionIDs)
	for _, sessionID := range sessionIDs {
		key, label, apps := workPatternModeKey(runsBySession[sessionID])
		if key == "" {
			continue
		}
		mode := modes[key]
		if mode == nil {
			mode = &modeAccumulator{
				label:      label,
				apps:       apps,
				sessionIDs: make(map[string]struct{}),
			}
			modes[key] = mode
		}
		mode.sessionIDs[sessionID] = struct{}{}
		mode.runs = append(mode.runs, runsBySession[sessionID]...)
	}
	modeKeys := make([]string, 0, len(modes))
	for key := range modes {
		modeKeys = append(modeKeys, key)
	}
	sort.Strings(modeKeys)
	for _, key := range modeKeys {
		mode := modes[key]
		projections = append(projections, buildWorkPatternProjection(
			WorkPatternScopeWorkMode,
			key,
			mode.label,
			mode.apps,
			cutoffAt,
			mode.runs,
			[]WorkPatternMetric{workPatternMetric(
				"recurring_session_count",
				float64(len(mode.sessionIDs)),
				"count",
				len(mode.sessionIDs),
				4,
			)},
		))
	}

	sort.SliceStable(projections, func(i, j int) bool {
		if projections[i].ScopeKind != projections[j].ScopeKind {
			return projections[i].ScopeKind < projections[j].ScopeKind
		}
		return projections[i].ScopeKey < projections[j].ScopeKey
	})
	return projections
}

func queryWorkPatternSourceEventsLegacy(
	store *ActivityStore,
	windowStart, cutoffAt int64,
) ([]workPatternSourceEvent, bool, workPatternSourceExclusionCounts, error) {
	if store == nil || store.db == nil {
		return nil, false, workPatternSourceExclusionCounts{}, errors.New(
			"activity store is unavailable",
		)
	}
	rows, err := store.db.Query(`
		SELECT row_id, session_id, session_start, session_end, timestamp, data
		FROM (
			SELECT
				e.id AS row_id,
				e.session_id AS session_id,
				s.start_time AS session_start,
				s.end_time AS session_end,
				e.timestamp AS timestamp,
				e.data AS data
			FROM activity_events e
			INNER JOIN activity_sessions s ON s.id = e.session_id
			WHERE e.timestamp >= ?
				AND e.timestamp <= ?
				AND COALESCE(s.triage_status, '') != 'protected'
				AND NOT EXISTS (
					SELECT 1
					FROM first_run_exclusions_v1 exclusion
					WHERE exclusion.source_kind = 'activity_session'
						AND exclusion.source_id = s.id
				)
			ORDER BY e.timestamp DESC, e.id DESC
			LIMIT ?
		)
		ORDER BY timestamp ASC, row_id ASC`,
		windowStart,
		cutoffAt,
		workPatternProfileMaximumEvents+1,
	)
	if err != nil {
		return nil, false, workPatternSourceExclusionCounts{}, fmt.Errorf(
			"query work pattern activity: %w",
			err,
		)
	}

	result := make([]workPatternSourceEvent, 0)
	for rows.Next() {
		var (
			item workPatternSourceEvent
			raw  string
		)
		if err := rows.Scan(
			&item.RowID,
			&item.SessionID,
			&item.SessionStart,
			&item.SessionEnd,
			&item.Timestamp,
			&raw,
		); err != nil {
			return nil, false, workPatternSourceExclusionCounts{}, fmt.Errorf(
				"scan work pattern activity: %w",
				err,
			)
		}
		var event activitymon.ActivityEvent
		if err := json.Unmarshal([]byte(raw), &event); err != nil {
			continue
		}
		item.AppKey = normalizeWorkPatternAppKey(
			event.AppBundleID,
			event.AppName,
		)
		if item.AppKey == "" {
			continue
		}
		item.AppName = workPatternDisplayAppName(event.AppName)
		result = append(result, item)
	}
	if err := rows.Err(); err != nil {
		rows.Close()
		return nil, false, workPatternSourceExclusionCounts{}, err
	}
	if err := rows.Close(); err != nil {
		return nil, false, workPatternSourceExclusionCounts{}, err
	}

	truncated := len(result) > workPatternProfileMaximumEvents
	if truncated {
		result = result[len(result)-workPatternProfileMaximumEvents:]
	}
	exclusions := workPatternSourceExclusionCounts{}
	if err := store.db.QueryRow(`
		SELECT COUNT(DISTINCT s.id)
		FROM activity_sessions s
		WHERE s.start_time <= ?
			AND s.end_time >= ?
			AND COALESCE(s.triage_status, '') = 'protected'`,
		cutoffAt,
		windowStart,
	).Scan(&exclusions.Protected); err != nil {
		return nil, false, workPatternSourceExclusionCounts{}, fmt.Errorf(
			"count protected work pattern sources: %w",
			err,
		)
	}
	if err := store.db.QueryRow(`
		SELECT COUNT(DISTINCT s.id)
		FROM activity_sessions s
		INNER JOIN first_run_exclusions_v1 exclusion
			ON exclusion.source_kind = 'activity_session'
			AND exclusion.source_id = s.id
		WHERE s.start_time <= ?
			AND s.end_time >= ?`,
		cutoffAt,
		windowStart,
	).Scan(&exclusions.FirstRun); err != nil {
		return nil, false, workPatternSourceExclusionCounts{}, fmt.Errorf(
			"count first run work pattern sources: %w",
			err,
		)
	}
	return result, truncated, exclusions, nil
}

func workPatternSourceHash(events []workPatternSourceEvent) string {
	type sourceIdentity struct {
		RowID     int64  `json:"rowId"`
		SessionID string `json:"sessionId"`
		Timestamp int64  `json:"timestamp"`
		AppKey    string `json:"appKey"`
	}
	identities := make([]sourceIdentity, 0, len(events))
	for _, event := range events {
		identities = append(identities, sourceIdentity{
			RowID:     event.RowID,
			SessionID: event.SessionID,
			Timestamp: event.Timestamp,
			AppKey:    event.AppKey,
		})
	}
	payload, _ := json.Marshal(identities)
	return workPatternHash(payload)
}

func sortedWorkPatternCapabilitySignals(
	signals []WorkPatternCapabilitySignal,
) []WorkPatternCapabilitySignal {
	result := append([]WorkPatternCapabilitySignal(nil), signals...)
	sort.SliceStable(result, func(i, j int) bool {
		if result[i].CapabilityKey != result[j].CapabilityKey {
			return result[i].CapabilityKey < result[j].CapabilityKey
		}
		if result[i].CreatedAt != result[j].CreatedAt {
			return result[i].CreatedAt < result[j].CreatedAt
		}
		return result[i].ProfileID < result[j].ProfileID
	})
	return result
}

func workPatternCapabilityProjections(
	signals []WorkPatternCapabilitySignal,
	cutoffAt int64,
) []WorkPatternProjection {
	signals = sortedWorkPatternCapabilitySignals(signals)
	result := make([]WorkPatternProjection, 0, len(signals))
	for _, signal := range signals {
		if signal.ProfileID == "" || signal.CapabilityKey == "" ||
			signal.EvaluationCount <= 0 || signal.CreatedAt > cutoffAt {
			continue
		}
		reliability := float64(0)
		if signal.ActionReliability != nil {
			reliability = workPatternClamp(*signal.ActionReliability)
		}
		coverage := workPatternClamp(
			float64(signal.QualifiedCount) /
				float64(max(signal.EvaluationCount, 1)),
		)
		decay := workPatternDecayWeight(signal.CreatedAt, cutoffAt)
		status := WorkPatternProfileStatusInsufficient
		if signal.Ready &&
			signal.Status == ShadowTaskLearningDecisionQualified &&
			signal.ActionReliability != nil {
			status = WorkPatternProfileStatusQualified
		}
		metrics := []WorkPatternMetric{
			enrichWorkPatternMetric(
				workPatternMetric(
					"action_reliability",
					reliability,
					"ratio",
					signal.QualifiedCount,
					5,
				),
				signal.CreatedAt,
				signal.CreatedAt,
				cutoffAt,
				coverage,
				0,
			),
			enrichWorkPatternMetric(
				workPatternMetric(
					"evaluated_outcome_count",
					float64(signal.EvaluationCount),
					"count",
					signal.EvaluationCount,
					5,
				),
				signal.CreatedAt,
				signal.CreatedAt,
				cutoffAt,
				coverage,
				0,
			),
			enrichWorkPatternMetric(
				workPatternMetric(
					"unknown_reasoning_count",
					float64(signal.UnknownReasoning),
					"count",
					signal.EvaluationCount,
					5,
				),
				signal.CreatedAt,
				signal.CreatedAt,
				cutoffAt,
				coverage,
				0,
			),
		}
		result = append(result, WorkPatternProjection{
			ScopeKind:    WorkPatternScopeCapability,
			ScopeKey:     signal.CapabilityKey,
			Label:        signal.CapabilityKey,
			EvidenceKind: WorkPatternEvidenceEvaluated,
			Status:       status,
			Confidence: workPatternClamp(
				reliability * coverage * decay,
			),
			SampleCount:  signal.EvaluationCount,
			SessionCount: signal.SourceContextCount,
			FreshnessAt:  signal.CreatedAt,
			Stability:    coverage,
			DecayWeight:  decay,
			Metrics:      metrics,
		})
	}
	return result
}

func workPatternCombinedSourceHash(
	events []workPatternSourceEvent,
	signals []WorkPatternCapabilitySignal,
) string {
	payload, _ := json.Marshal(struct {
		ActivityHash string                        `json:"activityHash"`
		Capabilities []WorkPatternCapabilitySignal `json:"capabilities"`
	}{
		ActivityHash: workPatternSourceHash(events),
		Capabilities: sortedWorkPatternCapabilitySignals(signals),
	})
	return workPatternHash(payload)
}

func workPatternCapabilityEvidence(
	snapshotID string,
	signals []WorkPatternCapabilitySignal,
	createdAt int64,
) []WorkPatternProfileEvidence {
	signals = sortedWorkPatternCapabilitySignals(signals)
	result := make([]WorkPatternProfileEvidence, 0, len(signals))
	for _, signal := range signals {
		if signal.ProfileID == "" || signal.CapabilityKey == "" {
			continue
		}
		payload, _ := json.Marshal(signal)
		contentHash := workPatternHash(payload)
		sourceKind := "shadow_capability_profile"
		sourceID := signal.ProfileID
		reason := "evaluated_capability_source"
		if signal.Learning != nil {
			sourceKind = taskContextSourceVerifiedShadowLearningKind
			sourceID = signal.Learning.MaterializationReceiptID
			reason = "verified_evaluated_capability_source"
		}
		result = append(result, WorkPatternProfileEvidence{
			ID: deterministicTaskEpisodeID(
				"work-pattern-profile-evidence",
				snapshotID+"\x00capability\x00"+signal.ProfileID+
					"\x00"+contentHash,
			),
			ProfileSnapshotID: snapshotID,
			SourceKind:        sourceKind,
			SourceID:          sourceID,
			ObservedAt:        signal.CreatedAt,
			ContentHash:       contentHash,
			Included:          true,
			Reason:            reason,
			CreatedAt:         createdAt,
		})
	}
	return result
}

func workPatternProfileEvidenceForEvents(
	snapshotID string,
	events []workPatternSourceEvent,
	truncated bool,
	exclusions workPatternSourceExclusionCounts,
	createdAt int64,
) []WorkPatternProfileEvidence {
	bySession := make(map[string][]workPatternSourceEvent)
	for _, event := range events {
		bySession[event.SessionID] = append(
			bySession[event.SessionID],
			event,
		)
	}
	sessionIDs := make([]string, 0, len(bySession))
	for sessionID := range bySession {
		sessionIDs = append(sessionIDs, sessionID)
	}
	sort.Strings(sessionIDs)
	result := make([]WorkPatternProfileEvidence, 0, len(sessionIDs)+3)
	for _, sessionID := range sessionIDs {
		items := bySession[sessionID]
		hash := workPatternSourceHash(items)
		observedAt := int64(0)
		for _, item := range items {
			observedAt = max(observedAt, item.Timestamp)
		}
		result = append(result, WorkPatternProfileEvidence{
			ID: deterministicTaskEpisodeID(
				"work-pattern-profile-evidence",
				snapshotID+"\x00"+sessionID+"\x00"+hash,
			),
			ProfileSnapshotID: snapshotID,
			SourceKind:        "activity_session",
			SourceID:          sessionID,
			ObservedAt:        observedAt,
			ContentHash:       hash,
			Included:          true,
			Reason:            "metric_source",
			CreatedAt:         createdAt,
		})
	}
	if truncated {
		result = append(result, WorkPatternProfileEvidence{
			ID: deterministicTaskEpisodeID(
				"work-pattern-profile-exclusion",
				snapshotID+"\x00operational_scan_truncated",
			),
			ProfileSnapshotID: snapshotID,
			SourceKind:        "activity_event_scan",
			SourceID:          "newest_events",
			Included:          false,
			Reason:            "operational_scan_truncated",
			CreatedAt:         createdAt,
		})
	}
	if exclusions.Protected > 0 {
		result = append(result, WorkPatternProfileEvidence{
			ID: deterministicTaskEpisodeID(
				"work-pattern-profile-exclusion",
				fmt.Sprintf(
					"%s\x00protected_sessions:%d",
					snapshotID,
					exclusions.Protected,
				),
			),
			ProfileSnapshotID: snapshotID,
			SourceKind:        "protected_activity",
			SourceID: fmt.Sprintf(
				"excluded_count:%d",
				exclusions.Protected,
			),
			Included:  false,
			Reason:    "privacy_excluded",
			CreatedAt: createdAt,
		})
	}
	if exclusions.FirstRun > 0 {
		result = append(result, WorkPatternProfileEvidence{
			ID: deterministicTaskEpisodeID(
				"work-pattern-profile-exclusion",
				fmt.Sprintf(
					"%s\x00first_run_sessions:%d",
					snapshotID,
					exclusions.FirstRun,
				),
			),
			ProfileSnapshotID: snapshotID,
			SourceKind:        "guided_first_run",
			SourceID: fmt.Sprintf(
				"excluded_count:%d",
				exclusions.FirstRun,
			),
			Included:  false,
			Reason:    firstRunContaminationReason,
			CreatedAt: createdAt,
		})
	}
	if exclusions.AmbientSystemEvent > 0 {
		result = append(result, WorkPatternProfileEvidence{
			ID: deterministicTaskEpisodeID(
				"work-pattern-profile-exclusion",
				fmt.Sprintf(
					"%s\x00ambient_system_events:%d",
					snapshotID,
					exclusions.AmbientSystemEvent,
				),
			),
			ProfileSnapshotID: snapshotID,
			SourceKind:        "ambient_system_surface",
			SourceID: fmt.Sprintf(
				"excluded_count:%d",
				exclusions.AmbientSystemEvent,
			),
			Included:  false,
			Reason:    "non_work_system_surface",
			CreatedAt: createdAt,
		})
	}
	return result
}

func buildWorkPatternProfileSnapshot(
	windowStart, cutoffAt int64,
	events []workPatternSourceEvent,
	truncated bool,
	exclusionCounts workPatternSourceExclusionCounts,
	capabilitySignals []WorkPatternCapabilitySignal,
	createdAt int64,
) (WorkPatternProfileSnapshot, []WorkPatternProfileEvidence, error) {
	metricEvents, ambientSystemEvents := filterWorkPatternSourceEvents(events)
	exclusionCounts.AmbientSystemEvent += ambientSystemEvents
	runs, transitions := deriveWorkPatternRuns(metricEvents)
	projections := buildWorkPatternProjections(runs, transitions, cutoffAt)
	projections = append(
		projections,
		workPatternCapabilityProjections(capabilitySignals, cutoffAt)...,
	)
	status := WorkPatternProfileStatusInsufficient
	confidence := float64(0)
	for _, projection := range projections {
		if projection.ScopeKind == WorkPatternScopeGlobal {
			status = projection.Status
			confidence = projection.Confidence
			break
		}
	}
	sessionSet := make(map[string]struct{})
	maxEventID := int64(0)
	for _, event := range metricEvents {
		sessionSet[event.SessionID] = struct{}{}
		maxEventID = max(maxEventID, event.RowID)
	}
	exclusions := make([]WorkPatternProfileExclusion, 0, 4)
	if truncated {
		exclusions = append(exclusions, WorkPatternProfileExclusion{
			SourceKind: "activity_event_scan",
			SourceID:   "newest_events",
			Reason:     "operational_scan_truncated",
		})
	}
	if exclusionCounts.Protected > 0 {
		exclusions = append(exclusions, WorkPatternProfileExclusion{
			SourceKind: "protected_activity",
			SourceID: fmt.Sprintf(
				"excluded_count:%d",
				exclusionCounts.Protected,
			),
			Reason: "privacy_excluded",
		})
	}
	if exclusionCounts.FirstRun > 0 {
		exclusions = append(exclusions, WorkPatternProfileExclusion{
			SourceKind: "guided_first_run",
			SourceID: fmt.Sprintf(
				"excluded_count:%d",
				exclusionCounts.FirstRun,
			),
			Reason: firstRunContaminationReason,
		})
	}
	if exclusionCounts.AmbientSystemEvent > 0 {
		exclusions = append(exclusions, WorkPatternProfileExclusion{
			SourceKind: "ambient_system_surface",
			SourceID: fmt.Sprintf(
				"excluded_count:%d",
				exclusionCounts.AmbientSystemEvent,
			),
			Reason: "non_work_system_surface",
		})
	}
	sourceHash := workPatternCombinedSourceHash(metricEvents, capabilitySignals)
	payload := workPatternProfilePayload{
		PolicyVersion:     WorkPatternProfilePolicyVersion,
		SourceWindowStart: windowStart,
		SourceCutoffAt:    cutoffAt,
		SourceMaxEventID:  maxEventID,
		SourceHash:        sourceHash,
		Status:            status,
		SampleCount:       len(runs),
		SessionCount:      len(sessionSet),
		Confidence:        confidence,
		Projections:       projections,
		Exclusions:        exclusions,
	}
	canonical, err := json.Marshal(payload)
	if err != nil {
		return WorkPatternProfileSnapshot{}, nil, err
	}
	idKey := strings.Join([]string{
		WorkPatternProfilePolicyVersion,
		fmt.Sprint(windowStart),
		fmt.Sprint(cutoffAt),
		sourceHash,
	}, "\x00")
	snapshot := WorkPatternProfileSnapshot{
		ID: deterministicTaskEpisodeID(
			"work-pattern-profile-snapshot",
			idKey,
		),
		PolicyVersion:     payload.PolicyVersion,
		SourceWindowStart: payload.SourceWindowStart,
		SourceCutoffAt:    payload.SourceCutoffAt,
		SourceMaxEventID:  payload.SourceMaxEventID,
		SourceHash:        payload.SourceHash,
		Status:            payload.Status,
		SampleCount:       payload.SampleCount,
		SessionCount:      payload.SessionCount,
		Confidence:        payload.Confidence,
		Projections:       payload.Projections,
		Exclusions:        payload.Exclusions,
		CanonicalJSON:     string(canonical),
		SHA256:            workPatternHash(canonical),
		CreatedAt:         createdAt,
	}
	evidence := workPatternProfileEvidenceForEvents(
		snapshot.ID,
		metricEvents,
		truncated,
		exclusionCounts,
		createdAt,
	)
	evidence = append(
		evidence,
		workPatternCapabilityEvidence(
			snapshot.ID,
			capabilitySignals,
			createdAt,
		)...,
	)
	return snapshot, evidence, nil
}

func scanWorkPatternProfileSnapshot(
	scanner interface{ Scan(dest ...any) error },
) (WorkPatternProfileSnapshot, error) {
	var result WorkPatternProfileSnapshot
	if err := scanner.Scan(
		&result.ID,
		&result.PolicyVersion,
		&result.SourceWindowStart,
		&result.SourceCutoffAt,
		&result.SourceMaxEventID,
		&result.SourceHash,
		&result.Status,
		&result.SampleCount,
		&result.SessionCount,
		&result.Confidence,
		&result.CanonicalJSON,
		&result.SHA256,
		&result.CreatedAt,
	); err != nil {
		return WorkPatternProfileSnapshot{}, err
	}
	var payload workPatternProfilePayload
	if err := json.Unmarshal([]byte(result.CanonicalJSON), &payload); err != nil {
		return WorkPatternProfileSnapshot{}, fmt.Errorf(
			"decode work pattern profile %s: %w",
			result.ID,
			err,
		)
	}
	if workPatternHash([]byte(result.CanonicalJSON)) != result.SHA256 {
		return WorkPatternProfileSnapshot{}, fmt.Errorf(
			"work pattern profile %s hash mismatch",
			result.ID,
		)
	}
	result.Projections = payload.Projections
	result.Exclusions = payload.Exclusions
	return result, nil
}

const workPatternProfileSelectColumns = `
	id, policy_version, source_window_start, source_cutoff_at,
	source_max_event_id, source_hash, status, sample_count, session_count,
	confidence, canonical_json, sha256, created_at`

// EnsureWorkPatternProfileSnapshot derives an immutable as-of projection from
// activity strictly no later than cutoffAt. Retries with the same source
// window and evidence return the existing row.
func (s *ActivityStore) EnsureWorkPatternProfileSnapshot(
	cutoffAt, createdAt int64,
) (WorkPatternProfileSnapshot, bool, error) {
	if s == nil || s.db == nil {
		return WorkPatternProfileSnapshot{}, false, errors.New(
			"activity store is unavailable",
		)
	}
	if cutoffAt <= 0 || createdAt <= 0 {
		return WorkPatternProfileSnapshot{}, false, errors.New(
			"work pattern profile requires stable cutoff and creation timestamps",
		)
	}
	windowStart := cutoffAt - workPatternProfileLookback.Milliseconds()
	if windowStart <= 0 {
		windowStart = 1
	}
	events, truncated, exclusionCounts, err := queryWorkPatternSourceEvents(
		s,
		windowStart,
		cutoffAt,
	)
	if err != nil {
		return WorkPatternProfileSnapshot{}, false, err
	}
	capabilitySignals, err := listWorkPatternCapabilitySignalsAt(
		s,
		cutoffAt,
	)
	if err != nil {
		return WorkPatternProfileSnapshot{}, false, err
	}
	snapshot, evidence, err := buildWorkPatternProfileSnapshot(
		windowStart,
		cutoffAt,
		events,
		truncated,
		exclusionCounts,
		capabilitySignals,
		createdAt,
	)
	if err != nil {
		return WorkPatternProfileSnapshot{}, false, err
	}

	tx, err := s.db.Begin()
	if err != nil {
		return WorkPatternProfileSnapshot{}, false, err
	}
	defer tx.Rollback()
	var existingHash string
	err = tx.QueryRow(`
		SELECT sha256
		FROM work_pattern_profile_snapshots_v1
		WHERE id = ?`,
		snapshot.ID,
	).Scan(&existingHash)
	switch {
	case err == nil:
		if existingHash != snapshot.SHA256 {
			return WorkPatternProfileSnapshot{}, false, fmt.Errorf(
				"work pattern profile %s has a different immutable payload",
				snapshot.ID,
			)
		}
		if err := tx.Rollback(); err != nil {
			return WorkPatternProfileSnapshot{}, false, err
		}
		existing, getErr := s.GetWorkPatternProfileSnapshot(snapshot.ID)
		return existing, false, getErr
	case !errors.Is(err, sql.ErrNoRows):
		return WorkPatternProfileSnapshot{}, false, err
	}

	if _, err := tx.Exec(`
		INSERT INTO work_pattern_profile_snapshots_v1 (
			id, policy_version, source_window_start, source_cutoff_at,
			source_max_event_id, source_hash, status, sample_count,
			session_count, confidence, canonical_json, sha256, created_at
		) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
		snapshot.ID,
		snapshot.PolicyVersion,
		snapshot.SourceWindowStart,
		snapshot.SourceCutoffAt,
		snapshot.SourceMaxEventID,
		snapshot.SourceHash,
		snapshot.Status,
		snapshot.SampleCount,
		snapshot.SessionCount,
		snapshot.Confidence,
		snapshot.CanonicalJSON,
		snapshot.SHA256,
		snapshot.CreatedAt,
	); err != nil {
		return WorkPatternProfileSnapshot{}, false, fmt.Errorf(
			"insert work pattern profile: %w",
			err,
		)
	}
	for _, item := range evidence {
		if _, err := tx.Exec(`
			INSERT INTO work_pattern_profile_evidence_v1 (
				id, profile_snapshot_id, source_kind, source_id,
				observed_at, content_hash, included, reason, created_at
			) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)`,
			item.ID,
			item.ProfileSnapshotID,
			item.SourceKind,
			item.SourceID,
			item.ObservedAt,
			item.ContentHash,
			item.Included,
			item.Reason,
			item.CreatedAt,
		); err != nil {
			return WorkPatternProfileSnapshot{}, false, fmt.Errorf(
				"insert work pattern profile evidence: %w",
				err,
			)
		}
	}
	if err := tx.Commit(); err != nil {
		return WorkPatternProfileSnapshot{}, false, err
	}
	return snapshot, true, nil
}

func (s *ActivityStore) GetWorkPatternProfileSnapshot(
	id string,
) (WorkPatternProfileSnapshot, error) {
	if s == nil || s.db == nil {
		return WorkPatternProfileSnapshot{}, errors.New(
			"activity store is unavailable",
		)
	}
	return scanWorkPatternProfileSnapshot(s.db.QueryRow(`
		SELECT `+workPatternProfileSelectColumns+`
		FROM work_pattern_profile_snapshots_v1
		WHERE id = ?`,
		strings.TrimSpace(id),
	))
}

func (s *ActivityStore) GetLatestWorkPatternProfileSnapshotAt(
	cutoffAt int64,
) (WorkPatternProfileSnapshot, error) {
	if s == nil || s.db == nil {
		return WorkPatternProfileSnapshot{}, errors.New(
			"activity store is unavailable",
		)
	}
	return scanWorkPatternProfileSnapshot(s.db.QueryRow(`
		SELECT `+workPatternProfileSelectColumns+`
		FROM work_pattern_profile_snapshots_v1
		WHERE source_cutoff_at <= ?
		ORDER BY source_cutoff_at DESC, created_at DESC, rowid DESC
		LIMIT 1`,
		cutoffAt,
	))
}

func (s *ActivityStore) ListWorkPatternProfileSnapshots(
	limit int,
) ([]WorkPatternProfileSnapshot, error) {
	if limit <= 0 {
		limit = workPatternProfileDefaultList
	}
	if limit > workPatternProfileMaximumList {
		limit = workPatternProfileMaximumList
	}
	rows, err := s.db.Query(`
		SELECT `+workPatternProfileSelectColumns+`
		FROM work_pattern_profile_snapshots_v1
		ORDER BY source_cutoff_at DESC, created_at DESC, rowid DESC
		LIMIT ?`,
		limit,
	)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	result := make([]WorkPatternProfileSnapshot, 0, limit)
	for rows.Next() {
		item, err := scanWorkPatternProfileSnapshot(rows)
		if err != nil {
			return nil, err
		}
		result = append(result, item)
	}
	return result, rows.Err()
}

func (s *ActivityStore) ListWorkPatternProfileEvidence(
	snapshotID string,
) ([]WorkPatternProfileEvidence, error) {
	rows, err := s.db.Query(`
		SELECT
			id, profile_snapshot_id, source_kind, source_id,
			observed_at, content_hash, included, reason, created_at
		FROM work_pattern_profile_evidence_v1
		WHERE profile_snapshot_id = ?
		ORDER BY observed_at ASC, id ASC`,
		strings.TrimSpace(snapshotID),
	)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	result := make([]WorkPatternProfileEvidence, 0)
	for rows.Next() {
		var item WorkPatternProfileEvidence
		if err := rows.Scan(
			&item.ID,
			&item.ProfileSnapshotID,
			&item.SourceKind,
			&item.SourceID,
			&item.ObservedAt,
			&item.ContentHash,
			&item.Included,
			&item.Reason,
			&item.CreatedAt,
		); err != nil {
			return nil, err
		}
		result = append(result, item)
	}
	return result, rows.Err()
}
