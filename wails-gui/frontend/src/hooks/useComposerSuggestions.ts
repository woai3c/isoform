import { useCallback, useEffect, useRef, useState } from "react";

import {
    GetComposerSuggestions,
    RegenerateComposerSuggestions,
} from "../../wailsjs/go/main/App";
// Imported from the shim directly (the real module Vite aliases to); the
// generated wailsjs types only refresh on a full wails build.
import { GetActiveHandoffChips, type HandoffEntry } from "@/lib/wails-shim-app";
import { EventsOn } from "../../wailsjs/runtime/runtime";

export interface ComposerSuggestionsBatch {
    id: string;
    generatedAt: number;
    suggestions: string[];
}

/** One active handoff surfaced as a composer chip. */
export interface ActiveHandoffChip {
    id: string;
    title: string;
}

interface UseComposerSuggestionsState {
    suggestions: string[];
    batchId: string | null;
    isLoading: boolean;
    isRefreshing: boolean;
}

interface UseComposerSuggestionsResult extends UseComposerSuggestionsState {
    // Active handoffs surfaced as prioritized chips.
    activeHandoffs: ActiveHandoffChip[];
    // TODO(debug-only): drop `refresh` when the debug refresh button is removed.
    refresh: () => Promise<void>;
}

// useComposerSuggestions subscribes to the backend's cached suggestion batch
// (refetched on `composer-suggestions:updated`) and, separately, active
// active handoff surfaced as a chip (refetched on `handoff:updated`). Neither
// is generated by the hook — the Go side owns generation.
export function useComposerSuggestions(): UseComposerSuggestionsResult {
    const [state, setState] = useState<UseComposerSuggestionsState>({
        suggestions: [],
        batchId: null,
        isLoading: true,
        isRefreshing: false,
    });
    const [activeHandoffs, setActiveHandoffs] = useState<ActiveHandoffChip[]>([]);
    const mountedRef = useRef(true);

    const fetchLatest = useCallback(async (markRefreshing: boolean) => {
        if (markRefreshing) {
            setState((prev) => ({ ...prev, isRefreshing: true }));
        }
        try {
            const batch =
                (await GetComposerSuggestions()) as ComposerSuggestionsBatch | null;
            if (!mountedRef.current) return;
            setState({
                suggestions: batch?.suggestions ?? [],
                batchId: batch?.id ?? null,
                isLoading: false,
                isRefreshing: false,
            });
        } catch (err) {
            if (!mountedRef.current) return;
            console.warn("[composer-suggestions] fetch failed", err);
            setState((prev) => ({
                ...prev,
                isLoading: false,
                isRefreshing: false,
            }));
        }
    }, []);

    const fetchHandoff = useCallback(async () => {
        try {
            const rows = ((await GetActiveHandoffChips(0)) ??
                []) as HandoffEntry[];
            if (!mountedRef.current) return;
            setActiveHandoffs(
                rows
                    .filter((entry) => entry && entry.id)
                    .map((entry) => ({ id: entry.id, title: entry.title })),
            );
        } catch (err) {
            if (!mountedRef.current) return;
            console.warn(
                "[composer-suggestions] handoff chip fetch failed",
                err,
            );
            setActiveHandoffs([]);
        }
    }, []);

    useEffect(() => {
        mountedRef.current = true;
        void fetchLatest(false);
        void fetchHandoff();
        const unsubSuggestions = EventsOn(
            "composer-suggestions:updated",
            () => {
                void fetchLatest(true);
            },
        );
        const unsubHandoff = EventsOn("handoff:updated", () => {
            void fetchHandoff();
        });
        return () => {
            mountedRef.current = false;
            unsubSuggestions?.();
            unsubHandoff?.();
        };
    }, [fetchLatest, fetchHandoff]);

    // TODO(debug-only): remove `refresh` when the refresh button is removed.
    const refresh = useCallback(async () => {
        setState((prev) => ({ ...prev, isRefreshing: true }));
        try {
            await Promise.all([RegenerateComposerSuggestions(), fetchHandoff()]);
        } catch (err) {
            console.warn("[composer-suggestions] refresh failed", err);
            if (mountedRef.current) {
                setState((prev) => ({ ...prev, isRefreshing: false }));
            }
        }
    }, [fetchHandoff]);

    return { ...state, activeHandoffs, refresh };
}
