func TestSkipTypes(t *testing.T) {
	cases := []struct {
		types []string
		skip  bool
	}{
		{[]string{"public.utf8-plain-text"}, false},
		{[]string{"public.utf8-plain-text", TypeConcealed}, true},
		{[]string{TypeTransient, "public.png"}, true},
		{[]string{"public.html", TypeAutoGenerated}, true},
		{nil, false},
	}
	for _, tc := range cases {
		if got := SkipTypes(tc.types); got != tc.skip {
			t.Fatalf("SkipTypes(%v) = %v, want %v", tc.types, got, tc.skip)
		}
	}
}

func TestKindOf(t *testing.T) {
	cases := map[string][]string{
		KindFile:  {"public.file-url", "public.utf8-plain-text"},
		KindURL:   {"public.url", "public.utf8-plain-text"},
		KindImage: {"public.png"},
		KindText:  {"public.html", "public.utf8-plain-text"},
		KindOther: {"com.example.private"},
	}
	for want, types := range cases {
		if got := KindOf(types); got != want {
			t.Fatalf("KindOf(%v) = %q, want %q", types, got, want)
		}
	}
	if HasText([]string{"public.png"}) || !HasText([]string{"public.url"}) {
		t.Fatal("HasText")
	}
}

func TestSensitiveSource(t *testing.T) {
	cases := []struct {
		bundle, name string
		want         bool
	}{
		{"com.1password.1password", "1Password", true},
		{"com.bitwarden.desktop", "Bitwarden", true},
		{"com.keepersecurity.passwordmanager", "Keeper", true},
		{"me.proton.pass.electron", "Proton Pass", true},
		{"com.apple.keychainaccess", "Keychain Access", true},
		{"com.example.vault", "My Password Vault", true},
		{"com.apple.Safari", "Safari", false},
		{"com.apple.Notes", "Notes", false},
	}
	for _, tc := range cases {
		if got := SensitiveSource(tc.bundle, tc.name); got != tc.want {
			t.Fatalf("SensitiveSource(%q, %q) = %v, want %v", tc.bundle, tc.name, got, tc.want)
		}
	}
	// Apps the user protects on the Privacy page count too.
	pii.AddUserSensitiveApp("com.example.diary", "Diary")
	t.Cleanup(func() { pii.RemoveUserSensitiveApp("com.example.diary") })
	if !SensitiveSource("com.example.diary.mac", "Diary") || !SensitiveSource("", "Diary") {
		t.Fatal("a user-protected app must be sensitive")
	}
}

func TestWithholdPreview(t *testing.T) {
	withheld := []string{
		"hX7#kq9!Lm", "Tr0ub4dor&3", "monkey1234", "123456",
		"d41d8cd98f00b204e9800998ecf8427e", "k3j4h5g6f7d8s9a0", "Quarterly", "",
	}
	for _, s := range withheld {
		if !WithholdPreview(s) {
			t.Fatalf("%q should keep no preview", s)
		}
	}
	kept := []string{"meeting notes", "https://example.com/pricing"}
	for _, s := range kept {
		if WithholdPreview(s) {
			t.Fatalf("%q should keep a preview", s)
		}
	}
}

func TestWithholdPreviewSecretsWithSpaces(t *testing.T) {
	withheld := []string{
		// A 12-word recovery phrase, as a wallet shows it, plain and numbered.
		"abandon ability able about above absent absorb abstract absurd abuse access accident",
		"1. legal 2. winner 3. thank 4. year 5. wave 6. sausage 7. worth 8. useful 9. legal 10. winner 11. thank 12. yellow",
		"zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo zoo",
		// A labelled secret whose words would survive redaction.
		"password: correct horse battery staple",
		"My passphrase is correct horse battery staple",
		"recovery key ABCD EFGH IJKL MNOP",
		"Your verification code: 482 913",
		"PIN 4 8 2 9",
		"密码 是 hunter two",
	}
	for _, s := range withheld {
		if !WithholdPreview(s) {
			t.Errorf("%q should keep no preview", s)
		}
		if got := Preview(s); got != "" {
			t.Errorf("Preview(%q) = %q, want none", s, got)
		}
	}
	kept := []string{
		"Ship the pricing deck before the review on Friday",
		// Fewer than 12 words, or capitals and punctuation, is ordinary text.
		"buy milk eggs bread",
		"Meet Anna at the cafe near the station after work today and bring the notes",
	}
	for _, s := range kept {
		if WithholdPreview(s) {
			t.Errorf("%q should keep a preview", s)
		}
	}
}

func TestPreviewRedactsSpacedCodes(t *testing.T) {
	for _, s := range []string{
		"Use 482 913 to sign in",
		"Use 482-913 to sign in",
		"Use 482.913 to sign in",
		"Card ending 4111 1111 1111 1111 is due",
	} {
		got := Preview(s)
		if strings.ContainsAny(got, "0123456789") {
			t.Errorf("Preview(%q) = %q keeps digits of a code", s, got)
		}
	}
	if got := Preview("Room 12 at 3 pm"); got != "Room 12 at 3 pm" {
		t.Errorf("short numbers stay: %q", got)
	}
}

func TestPreview(t *testing.T) {
	if got := Preview("  Ship   the\npricing deck  "); got != "Ship the pricing deck" {
		t.Fatalf("whitespace: %q", got)
	}
	if got := Preview("hX7#kq9!Lm"); got != "" {
		t.Fatalf("a password keeps no preview: %q", got)
	}
	if got := Preview("Your code is 482913 do not share"); strings.Contains(got, "482913") {
		t.Fatalf("a one-time code must be redacted: %q", got)
	}
	if got := Preview("https://app.example.com/reset-password/9f8a7b6c5d4e3f2a1b0c"); got != "https://app.example.com/reset-password/..." {
		t.Fatalf("a token in a link path must go: %q", got)
	}
	if got := Preview("https://app.example.com/invite/Zk9xQ2tqR3ZtY29kZQ"); got != "https://app.example.com/invite/..." {
		t.Fatalf("an invite token must go: %q", got)
	}
	if got := Preview("https://github.com/example/isoform/pull/12"); got != "https://github.com/example/isoform/pull/12" {
		t.Fatalf("a plain link path stays: %q", got)
	}
	if got := Preview("https://accounts.example.com/reset?token=abc123#step2"); got != "https://accounts.example.com/reset" {
		t.Fatalf("link keeps only scheme, host and path: %q", got)
	}
	if got := Preview("https://example.com/people/ann@example.com"); strings.Contains(got, "ann@example.com") {
		t.Fatalf("an email address in a link path must be redacted: %q", got)
	}
	if got := Preview("Email ann@example.com about it"); strings.Contains(got, "ann@example.com") {
		t.Fatalf("an email address must be redacted: %q", got)
	}
	long := strings.Repeat("word ", 100)
	got := Preview(long)
	if !strings.HasSuffix(got, "...") || len([]rune(got)) > PreviewMaxRunes+3 {
		t.Fatalf("long text is cut: %d runes", len([]rune(got)))
	}
	if Preview("   ") != "" {
		t.Fatal("blank text keeps nothing")
	}
}
