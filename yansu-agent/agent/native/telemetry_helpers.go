// applyErrorTelemetryProperties exports only a stable error class and numeric
// upstream response metadata. Error strings and even redacted response bodies
// can contain private prompt text echoed by a provider, so they stay local.
func applyErrorTelemetryProperties(props map[string]any, err error) {
	props["error_kind"] = classifyStepError(err)
	var upstream *HTTPError
	if errors.As(err, &upstream) && upstream != nil {
		props["status_code"] = upstream.Status
		props["upstream_body_bytes"] = len(upstream.Body)
	}
}

// classifyPairingWording reports which family of pairing-error wording
// the upstream returned, so the agent.tool_pairing.detected event can
// be sliced in PostHog: anthropic-native vs sub2api-relayed (OpenAI).
// Returns "anthropic" / "openai" / "unknown".
func classifyPairingWording(err error) string {
	if err == nil {
		return "unknown"
	}
	// errors.As (vs direct .(*HTTPError) assertion) unwraps fmt.Errorf
	// %w wrappers a future caller might add, and the explicit he != nil
	// guard catches the typed-nil case where err is non-nil but the
	// concrete *HTTPError under it is. Same idiom applied to every
	// *HTTPError extraction in this package — see PR #1893 review.
	var he *HTTPError
	if !errors.As(err, &he) || he == nil {
		return "unknown"
	}
	body := he.Body
	switch {
	case strings.Contains(body, "tool_call_id") || strings.Contains(body, "tool_call_ids"):
		return "openai"
	case strings.Contains(body, "tool_use_id") || strings.Contains(body, "tool_use ids"):
		return "anthropic"
	default:
		return "unknown"
	}
}

// pairingBodyDigest returns the first 16 hex chars of SHA256(body) for local
// diagnostics. Body-derived identifiers are not included in telemetry.
func pairingBodyDigest(err error) string {
	if err == nil {
		return ""
	}
	var he *HTTPError
	if !errors.As(err, &he) || he == nil {
		return ""
	}
	sum := sha256.Sum256([]byte(he.Body))
	return hex.EncodeToString(sum[:])[:16]
}

// orphanIDPattern extracts the first looks-like-an-anthropic / openai
// tool id from a pairing-error body. Anthropic IDs match
// ^[a-zA-Z0-9_-]+$ (typically `toolu_*` or `call_*`); the error body
// usually mentions the id alongside the keyword tool_call_id or
// tool_use_id. We try a small set of stable patterns rather than
// JSON-parsing because the body shape varies across upstream proxies
// (Anthropic native, sub2api, Kimi-via-anthropic, etc.) and the id
// itself is always a contiguous safe-char token.
// pairingDumpUnsafeChars matches any character that isn't safe to
// embed directly in a filesystem path component. Used to sanitize
// cfg.TraceID before composing the pairing-dump filename: even though
// TraceID is currently generated by our own UI (UUID) and the dump
// path is opt-in via YANSU_DUMP_PAIRING_BODY, defensive sanitization
// keeps the call safe under a future change that wires TraceID up
// from a less-trusted source (e.g. forwarded HTTP header). Anything
// not in [a-zA-Z0-9_-] is replaced with `_`, neutralising path
// traversal (`../`), separator injection (`/`, `\`), null bytes,
// and Windows drive prefixes.
var pairingDumpUnsafeChars = regexp.MustCompile(`[^a-zA-Z0-9_-]`)

var orphanIDPatterns = []*regexp.Regexp{
	// "tool_call_id call_abc123 is not found"
	// "tool_use_id toolu_abc123 found in `tool_result`"
	// "blocks: call_abc123."   /  "ids: toolu_abc123,"
	regexp.MustCompile(`tool_(?:call|use)[_ ]id[^a-zA-Z0-9_-]+([a-zA-Z0-9_-]+)`),
	regexp.MustCompile(`blocks?:\s*([a-zA-Z0-9_-]{6,})`),
	regexp.MustCompile(`ids?\s*:\s*([a-zA-Z0-9_-]{6,})`),
}

// extractOrphanToolName parses err's body for the orphan tool id, then
// looks that id up in the supplied messages slice's tool_use blocks
// to recover the human-readable tool name (Read / Bash / Edit /
// WebFetch / ...). Empty string is returned when:
//   - the err isn't an *HTTPError (no body to parse)
//   - no id-shaped token is found in the body
//   - the id is found but no matching tool_use exists in messages
//     (which is exactly what makes it an orphan — but means we have
//     no name to attach)
//
// Used by the loop's agentloop.tool_pairing.detected telemetry event
// so PostHog dashboards can break down orphan frequency by tool name
// (e.g. "WebFetch triggers orphans 5x more than Read"). Pure best
// effort — when extraction fails the event still fires with the
// orphan_tool_name property set to empty.
func extractOrphanToolName(err error, messages []Message) string {
	if err == nil {
		return ""
	}
	var he *HTTPError
	if !errors.As(err, &he) || he == nil {
		return ""
	}
	body := he.Body
	if body == "" {
		return ""
	}
	var orphanID string
	for _, pat := range orphanIDPatterns {
		m := pat.FindStringSubmatch(body)
		if len(m) >= 2 {
			orphanID = m[1]
			break
		}
	}
	if orphanID == "" {
		return ""
	}
	// Walk assistant messages looking for a tool_use block with the
	// matching ID. The orphan condition is "no matching tool_use" —
	// but the way pairing errors propagate, the id is often present in
	// the message slice we just tried to send (the upstream is
	// complaining about a tool_result that references this id, and
	// there IS a tool_use with this id somewhere — just not in the
	// expected position). So this lookup hits more often than not.
	for _, m := range messages {
		if m.Role != "assistant" {
			continue
		}
		blocks, ok := m.Content.([]ContentBlock)
		if !ok {
			continue
		}
		for _, b := range blocks {
			if b.Type == "tool_use" && b.ID == orphanID {
				return b.Name
			}
		}
	}
	return ""
}

// dumpRequestBodyForPairingError writes the full messages slice as
// JSON to a per-trace file under $TMPDIR/yansu-pairing-dumps/, but
// ONLY when the operator opts in via YANSU_DUMP_PAIRING_BODY=1. The
// gate is deliberate: messages may be several MB when images are
// attached, and JSON-marshalling + writing on every pairing error
// would (a) burn 10-100ms on the error path, (b) pile up large dump
// files with no automatic cleanup, and (c) put user conversation
// content (potentially sensitive) on disk by default. The opt-in
// flips it to "developer triages a known recurrence" mode: enable
// the env var, reproduce once, grep the file, disable. Generic
// failures (any other error) deliberately don't dump — only the
// tool_call_id pairing class, which is what we're investigating.
//
// All errors here are swallowed and logged; the dump is a diagnostic
// aid, never load-bearing.
func dumpRequestBodyForPairingError(cfg *LoopConfig, messages []Message, pairingErr error) {
	if os.Getenv("YANSU_DUMP_PAIRING_BODY") != "1" {
		return
	}
	dir := filepath.Join(os.TempDir(), "yansu-pairing-dumps")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		log.Printf("[pairing-dump] mkdir failed: %v — dump skipped", err)
		return
	}
	// Sanitize traceID before embedding in the filename. See
	// pairingDumpUnsafeChars comment for the threat model — we treat
	// TraceID as untrusted on principle even though today it's our own
	// UUID. Also cap the slug length to keep filenames sane on
	// filesystems with NAME_MAX limits (ext4: 255 bytes).
	traceSlug := pairingDumpUnsafeChars.ReplaceAllString(cfg.TraceID, "_")
	if traceSlug == "" {
		traceSlug = "no-trace"
	}
	if len(traceSlug) > 64 {
		traceSlug = traceSlug[:64]
	}
	fname := fmt.Sprintf("%s-%s.json", time.Now().UTC().Format("20060102T150405Z"), traceSlug)
	path := filepath.Join(dir, fname)

	payload := map[string]any{
		"trace_id": cfg.TraceID,
		"run_id":   cfg.RunID,
		"model_id": cfg.ModelID,
		"error":    pairingErr.Error(),
		"messages": messages,
	}
	body, err := json.MarshalIndent(payload, "", "  ")
	if err != nil {
		log.Printf("[pairing-dump] marshal failed trace=%s: %v", cfg.TraceID, err)
		return
	}
	if err := os.WriteFile(path, body, 0o600); err != nil {
		log.Printf("[pairing-dump] write failed path=%s: %v", path, err)
		return
	}
	log.Printf("[pairing-dump] wrote %d bytes to %s (trace=%s) — share this file when triaging tool_call_id-not-found", len(body), path, cfg.TraceID)
}

// messagesFingerprint summarises a messages slice in a privacy-safe,
// fixed-size shape suitable for PostHog event properties. The point is
// to let dashboards answer "did this 400 happen with empty tool_use_ids
// in our request body?" without ever shipping the body itself.
//
// Returned map shape (all under 200 bytes total per call):
//
//	messages_count             total messages
//	empty_tool_use_id_count    tool_use blocks with ID==""
//	empty_tool_result_id_count tool_result blocks with ToolUseID==""
//	last_msg_role              role of the last message
//	last_msg_block_types       comma-joined block types of the last message
//	tool_use_ids_digest        first-8-hex of sha256(concat(all tool_use ids))
//
// The digest lets us group "same set of tool_use ids" without exposing
// the ids themselves; identical digests across error events mean the
// same broken state was sent twice.
func messagesFingerprint(messages []Message) map[string]any {
	emptyToolUseIDs := 0
	emptyToolResultIDs := 0
	idBuilder := &strings.Builder{}
	for _, m := range messages {
		blocks, ok := m.Content.([]ContentBlock)
		if !ok {
			continue
		}
		for _, b := range blocks {
			switch b.Type {
			case "tool_use":
				if b.ID == "" {
					emptyToolUseIDs++
				} else {
					idBuilder.WriteString(b.ID)
					idBuilder.WriteByte(0)
				}
			case "tool_result":
				if b.ToolUseID == "" {
					emptyToolResultIDs++
				}
			}
		}
	}

	lastRole := ""
	lastBlockTypes := ""
	if n := len(messages); n > 0 {
		lastRole = messages[n-1].Role
		if blocks, ok := messages[n-1].Content.([]ContentBlock); ok {
			parts := make([]string, 0, len(blocks))
			for _, b := range blocks {
				parts = append(parts, b.Type)
			}
			lastBlockTypes = strings.Join(parts, ",")
		}
	}

	digest := ""
	if idBuilder.Len() > 0 {
		sum := sha256.Sum256([]byte(idBuilder.String()))
		digest = hex.EncodeToString(sum[:])[:16]
	}

	return map[string]any{
		"messages_count":             len(messages),
		"empty_tool_use_id_count":    emptyToolUseIDs,
		"empty_tool_result_id_count": emptyToolResultIDs,
		"last_msg_role":              lastRole,
		"last_msg_block_types":       lastBlockTypes,
		"tool_use_ids_digest":        digest,
	}
}

// classifyLoopError buckets the loop's terminal error into a small set
// of strings that are useful as a PostHog property: panic, ctx_cancel,
// silent_turn, max_turns, http_4xx, http_5xx, history_load, client_init,
// unknown. Error text is never exported alongside the bucket because
// upstream errors can echo private prompt content.
func classifyLoopError(err error) string {
	if err == nil {
		return ""
	}
	if errors.Is(err, ErrSilentTurn) {
		return "silent_turn"
	}
	if errors.Is(err, ErrLoopGuardStuck) {
		return "tool_loop_guard"
	}
	if errors.Is(err, ErrAPICircuitBreaker) {
		return "api_circuit_breaker"
	}
	if errors.Is(err, context.Canceled) || errors.Is(err, context.DeadlineExceeded) {
		return "ctx_cancel"
	}
	msg := err.Error()
	switch {
	case strings.HasPrefix(msg, "panic: "):
		return "panic"
	case strings.Contains(msg, "max turns reached"):
		return "max_turns"
	case strings.Contains(msg, "load history"):
		return "history_load"
	case strings.HasPrefix(msg, "client required") || strings.Contains(msg, "Emit is required"):
		return "client_init"
	}
	var he *HTTPError
	if errors.As(err, &he) && he != nil {
		if he.Status >= 500 {
			return "http_5xx"
		}
		if he.Status >= 400 {
			return "http_4xx"
		}
	}
	return "unknown"
}

// toolResultSizeBytes returns the byte size of a tool_result block's
// rendered Content, used as a step.tool.completed property so the
// dashboard can spot tools that flood the context window. We sum the
// string form of plain-text results and the JSON length of multi-block
// results; an exact accounting of model-side tokens would require a
// tokenizer pass we don't want on every tool call. Bytes are close
// enough for "this tool returned 200 KB of HTML" signal.
func toolResultSizeBytes(blk ContentBlock) int {
	switch c := blk.Content.(type) {
	case string:
		return len(c)
	case []ContentBlock:
		// Multi-block results (e.g. Read-image returning text+image).
		// Marshal-and-measure costs a small allocation per tool call,
		// which is fine — these results are usually small and rare.
		buf, err := json.Marshal(c)
		if err != nil {
			return 0
		}
		return len(buf)
	default:
		return 0
	}
}

// classifyCompletionReason returns the lobehub-aligned run-level
// terminal label for the loop's exit condition. Sibling to
// classifyLoopError / classifyStepError but coarser: it describes the
// SHAPE of how the run ended rather than which error bucket it landed
// in. Phase 1+ dashboards render a completion_reason pie chart;
// Phase 2 pattern checker uses it to split user-interrupt traces
// from genuine failures.
//
// Categories:
//   - done           → runErr == nil (normal end_turn completion)
//   - silent_turn    → ErrSilentTurn (model gave up after recovery nudges)
//   - interrupted    → ctx.Canceled / ctx.DeadlineExceeded (user/timeout)
//   - max_steps      → "max turns reached" (MaxTurns guard tripped)
//   - error          → everything else (HTTP errors, pairing failures,
//     panics — kind / error_kind carry the detail)
//
// Stable additive contract — buckets only get added, never renamed.
// Mirrors lobehub ExecutionSnapshot.completionReason without their
// `cost_limit` / `waiting_for_human` values (we don't support those
// features yet; add when we do).
func classifyCompletionReason(runErr error) string {
	if runErr == nil {
		return "done"
	}
	if errors.Is(runErr, ErrSilentTurn) {
		return "silent_turn"
	}
	if errors.Is(runErr, context.Canceled) || errors.Is(runErr, context.DeadlineExceeded) {
		return "interrupted"
	}
	if errors.Is(runErr, ErrAPICircuitBreaker) {
		return "api_circuit_breaker"
	}
	if strings.Contains(runErr.Error(), "max turns reached") {
		return "max_steps"
	}
	return "error"
}

// classifyStepError buckets a single-step (LLM call or tool call) error
// into a finer-grained taxonomy than classifyLoopError. The Phase 0
// monitoring dashboard and the Phase 2/3 error-pattern checker both
// rely on these labels to group recurring failures across users and
// across deploys, so the set is deliberately stable: new buckets only
// get added, existing ones never renamed.
//
// Categories (in priority order — first match wins):
//
//   - ctx_cancel         user/parent context cancellation
//   - timeout            ctx deadline exceeded OR explicit "timeout" in body
//   - pairing            tool_use / tool_result id mismatch (IsToolPairingError)
//   - rate_limit         HTTP 429
//   - context_overflow   HTTP 400 with "prompt is too long" / "context_length" / "exceeded model token limit"
//   - request_too_large  HTTP 400/413 byte-size limit ("total message size N exceeds limit 2097152") — a BYTE limit, distinct from context_overflow (a TOKEN limit); fix is image down-scaling/pruning, not a schema patch. Must beat schema_mismatch (shared "invalid_request" envelope).
//   - schema_mismatch    HTTP 400 with schema / validation phrasings
//   - upstream_5xx       HTTP 5xx
//   - upstream_4xx       any other HTTP 4xx
//   - network            transport / connection errors (no HTTP status)
//   - silent_turn        ErrSilentTurn sentinel
//   - tool_loop_guard    ErrLoopGuardStuck — same tool called N times with identical args (run-terminal)
//   - api_circuit_breaker ErrAPICircuitBreaker — consecutive transient API failures (429/5xx) exhausted cross-turn retry budget (run-terminal)
//   - max_turns          MaxTurns guard tripped ("max turns reached") — run-terminal
//   - other              fallback
//
// tool_loop_guard and max_turns are RUN-terminal sentinels that flow
// through run.error rather than step.llm.error, but classifying them
// here keeps a single `error_kind` taxonomy so the Phase 2/3 pattern
// checker doesn't have to special-case event sources. Without this,
// both fall into "other" and lose all triage signal in the bucketing
// table (Phase 2 pattern checker would see a giant generic "other"
// bucket containing two qualitatively different harness terminations).
//
// The empty string is reserved for "no error" (err == nil) so dashboards
// can group `error_kind = ”` as the success bucket without a separate
// null check.
func classifyStepError(err error) string {
	if err == nil {
		return ""
	}
	if errors.Is(err, ErrSilentTurn) {
		return "silent_turn"
	}
	if errors.Is(err, ErrLoopGuardStuck) {
		return "tool_loop_guard"
	}
	if errors.Is(err, ErrAPICircuitBreaker) {
		return "api_circuit_breaker"
	}
	if errors.Is(err, context.Canceled) {
		return "ctx_cancel"
	}
	if errors.Is(err, context.DeadlineExceeded) {
		return "timeout"
	}
	if IsToolPairingError(err) {
		return "pairing"
	}
	var he *HTTPError
	if errors.As(err, &he) && he != nil {
		body := strings.ToLower(he.Body)
		// Request-body BYTE-size limit, checked before the status switch so
		// it catches both the Kimi/Moonshot 400 ("total message size N
		// exceeds limit 2097152") and a generic 413 — and, critically, wins
		// over the schema_mismatch branch below, whose "invalid_request"
		// match would otherwise capture this body and send the pattern
		// checker chasing a schema fix instead of image down-scaling /
		// pruning (see EnforceRequestByteBudget in image_budget.go). This is
		// a BYTE limit, orthogonal to context_overflow (a TOKEN limit).
		if strings.Contains(body, "total message size") ||
			strings.Contains(body, "request too large") ||
			strings.Contains(body, "request entity too large") ||
			strings.Contains(body, "payload too large") ||
			strings.Contains(body, "content too large") ||
			(strings.Contains(body, "message size") && strings.Contains(body, "exceed")) {
			return "request_too_large"
		}
		switch he.Status {
		case 429:
			return "rate_limit"
		case 400:
			// Context-window overflow has stable Anthropic/OpenAI phrasings.
			// Match both before falling through to the generic 4xx bucket so
			// the pattern checker can recommend compression-strategy fixes
			// distinctly from schema-fix patches.
			if strings.Contains(body, "prompt is too long") ||
				strings.Contains(body, "context_length") ||
				strings.Contains(body, "context length") ||
				strings.Contains(body, "maximum context") ||
				strings.Contains(body, "too many tokens") ||
				// Anthropic's production phrasing observed in real
				// traces: "Invalid request: Your request exceeded
				// model token limit: 262144 (requested: 407967)".
				// Generalised so a "requested:N exceeded token limit:M"
				// re-ordering also matches.
				(strings.Contains(body, "exceeded") && strings.Contains(body, "token limit")) {
				return "context_overflow"
			}
			if strings.Contains(body, "schema") ||
				strings.Contains(body, "validation") ||
				strings.Contains(body, "invalid_request") ||
				strings.Contains(body, "did not match") {
				return "schema_mismatch"
			}
		}
		if he.Status >= 500 {
			return "upstream_5xx"
		}
		if he.Status >= 400 {
			return "upstream_4xx"
		}
	}
	// Best-effort transport / network classification. Plain message
	// substring checks because Go's net package surfaces these as wrapped
	// *net.OpError / *url.Error and unwrapping each variant adds noise
	// without changing the bucket.
	msg := strings.ToLower(err.Error())
	switch {
	case strings.Contains(msg, "timeout"), strings.Contains(msg, "deadline exceeded"):
		return "timeout"
	case strings.Contains(msg, "connection refused"),
		strings.Contains(msg, "connection reset"),
		strings.Contains(msg, "no such host"),
		strings.Contains(msg, "broken pipe"),
		strings.Contains(msg, "eof"),
		strings.Contains(msg, "tls"),
		strings.Contains(msg, "dial tcp"):
		return "network"
	case strings.Contains(msg, "max turns reached"):
		// Run-terminal sentinel from loop.go's MaxTurns guard. Local
		// string (never from upstream body) so a plain Contains is
		// safe — kept here at the tail so an HTTPError carrying the
		// phrase in its body still classifies on status first.
		return "max_turns"
	}
	return "other"
}
